package formatter_test

import (
	"reflect"
	"testing"

	"github.com/ajitpratap0/GoSQLX/pkg/formatter"
	"github.com/ajitpratap0/GoSQLX/pkg/gosqlx"
	"github.com/ajitpratap0/GoSQLX/pkg/models"
	"github.com/ajitpratap0/GoSQLX/pkg/sql/ast"
	"github.com/ajitpratap0/GoSQLX/pkg/sql/keywords"
)

func TestDialectConstructsRoundTripAndInspection(t *testing.T) {
	cases := []struct {
		dialect keywords.SQLDialect
		sql     string
	}{
		{keywords.DialectSnowflake, `SELECT * FROM t PIVOT (SUM(amt) FOR month IN (ANY ORDER BY month) DEFAULT ON NULL (0)) AS p`},
		{keywords.DialectSnowflake, `SELECT * FROM t PIVOT (SUM(amt) FOR month IN ('JAN', 'FEB') DEFAULT ON NULL (0)) AS p`},
		{keywords.DialectClickHouse, `SELECT * FROM hits FINAL SAMPLE 0.1 WHERE x = 1`},
		{keywords.DialectClickHouse, `SELECT * FROM hits FINAL SAMPLE 1/10 OFFSET 1/2 WHERE x = 1`},
		{keywords.DialectClickHouse, `SELECT * FROM hits FINAL`},
		{keywords.DialectClickHouse, `SELECT * FROM hits SAMPLE 0.1`},
		{keywords.DialectClickHouse, `SELECT * FROM hits AS h FINAL SAMPLE 0.1`},
		{keywords.DialectSQLServer, `INSERT TOP (10) INTO t (a) SELECT a FROM s`},
		{keywords.DialectSQLServer, `INSERT TOP (10) PERCENT INTO t (a) SELECT a FROM s`},
		{keywords.DialectSQLServer, `INSERT TOP (@n) t (a) SELECT a FROM s`},
		{keywords.DialectSQLServer, `INSERT "TOP" (a) SELECT a FROM s`},
		{keywords.DialectPostgreSQL, `CREATE TABLE t (id bigint GENERATED ALWAYS AS IDENTITY (START WITH 10 INCREMENT BY 5) PRIMARY KEY, b int GENERATED BY DEFAULT AS IDENTITY NOT NULL, c int NOT NULL GENERATED ALWAYS AS IDENTITY)`},
		{keywords.DialectMySQL, `ALTER TABLE t PARTITION BY RANGE (YEAR(d)) (PARTITION p0 VALUES LESS THAN (2020), PARTITION p1 VALUES LESS THAN MAXVALUE)`},
		{keywords.DialectMySQL, `ALTER TABLE t ADD PARTITION (PARTITION p2 VALUES LESS THAN (2030))`},
		{keywords.DialectMySQL, `ALTER TABLE t DROP PARTITION p0`},
		{keywords.DialectMySQL, `ALTER TABLE t TRUNCATE PARTITION p1`},
		{keywords.DialectMySQL, `ALTER TABLE t REORGANIZE PARTITION p1 INTO (PARTITION p2 VALUES LESS THAN (2030), PARTITION p3 VALUES LESS THAN MAXVALUE)`},
		{keywords.DialectMySQL, `ALTER TABLE t REMOVE PARTITIONING`},
		{keywords.DialectPostgreSQL, `SELECT * FROM ROWS FROM (generate_series(1,3), unnest(ARRAY['a','b'])) WITH ORDINALITY AS r(n, s, i)`},
		{keywords.DialectPostgreSQL, `SELECT * FROM ROWS FROM (f(x) AS (a int, b text))`},
		{keywords.DialectPostgreSQL, `SELECT (ARRAY[1,2,3])[2]`},
		{keywords.DialectPostgreSQL, `SELECT ARRAY[1,2,3][2]`},
		{keywords.DialectPostgreSQL, `SELECT ARRAY[[1,2],[3,4]][1][2]`},
		{keywords.DialectPostgreSQL, `SELECT ARRAY[1,2,3][1:2]`},
	}
	for _, dialect := range []keywords.SQLDialect{keywords.DialectPostgreSQL, keywords.DialectSnowflake, keywords.DialectSQLServer, keywords.DialectOracle} {
		cases = append(cases, struct {
			dialect keywords.SQLDialect
			sql     string
		}{dialect, `SELECT a, b, SUM(c) FROM t GROUP BY GROUPING SETS ((a), ROLLUP(b), CUBE(a, b), ())`})
	}
	for _, tc := range cases {
		t.Run(string(tc.dialect)+"/"+tc.sql, func(t *testing.T) {
			tree, err := gosqlx.ParseWithDialect(tc.sql, tc.dialect)
			if err != nil {
				t.Fatal(err)
			}
			defer ast.ReleaseAST(tree)
			checkDialectConstructInspection(t, tree)
			formatted, err := gosqlx.FormatWithDialect(tc.sql, gosqlx.DefaultFormatOptions(), tc.dialect)
			if err != nil {
				t.Fatal(err)
			}
			outputs := []string{tree.SQL(), formatted, formatter.FormatAST(tree, ast.CompactStyle()), formatter.FormatAST(tree, ast.ReadableStyle())}
			clearDialectConstructLocations(reflect.ValueOf(tree.Statements))
			for _, output := range outputs {
				again, err := gosqlx.ParseWithDialect(output, tc.dialect)
				if err != nil {
					t.Fatalf("reparse %q: %v", output, err)
				}
				defer ast.ReleaseAST(again)
				clearDialectConstructLocations(reflect.ValueOf(again.Statements))
				if !reflect.DeepEqual(tree.Statements, again.Statements) {
					t.Errorf("AST changed after rendering %q", output)
				}
				checkDialectConstructInspection(t, again)
			}
		})
	}
}

// Source positions change with whitespace; every other field must be identical.
func clearDialectConstructLocations(v reflect.Value) {
	if !v.IsValid() {
		return
	}
	if v.Type() == reflect.TypeFor[models.Location]() && v.CanSet() {
		v.SetZero()
		return
	}
	switch v.Kind() {
	case reflect.Interface, reflect.Pointer:
		if !v.IsNil() {
			clearDialectConstructLocations(v.Elem())
		}
	case reflect.Struct:
		for i := 0; i < v.NumField(); i++ {
			if v.Type().Field(i).IsExported() {
				clearDialectConstructLocations(v.Field(i))
			}
		}
	case reflect.Slice:
		for i := 0; i < v.Len(); i++ {
			clearDialectConstructLocations(v.Index(i))
		}
	}
}

// Compare traversal against the fields themselves so a missing Children edge
// cannot hide an expression from the acceptance tests.
func checkDialectConstructInspection(t *testing.T, tree *ast.AST) {
	t.Helper()
	visited := map[ast.Expression]bool{}
	ast.Inspect(tree, func(node ast.Node) bool {
		if e, ok := node.(ast.Expression); ok {
			visited[e] = true
		}
		return true
	})
	var check func(reflect.Value)
	check = func(v reflect.Value) {
		if !v.IsValid() {
			return
		}
		if v.Kind() == reflect.Pointer && v.IsNil() {
			return
		}
		if v.CanInterface() {
			if e, ok := v.Interface().(ast.Expression); ok && !visited[e] {
				t.Errorf("expression %T (%s) is not reachable through Inspect", e, e.TokenLiteral())
			}
		}
		switch v.Kind() {
		case reflect.Interface, reflect.Pointer:
			if !v.IsNil() {
				check(v.Elem())
			}
		case reflect.Struct:
			for i := 0; i < v.NumField(); i++ {
				if v.Type().Field(i).IsExported() {
					check(v.Field(i))
				}
			}
		case reflect.Slice:
			for i := 0; i < v.Len(); i++ {
				check(v.Index(i))
			}
		}
	}
	check(reflect.ValueOf(tree.Statements))
}
