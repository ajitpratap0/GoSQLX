// Column constraint kinds
//
// ColumnConstraint.Type holds the constraint kind. Besides the SQL-standard
// kinds (NOT NULL, NULL, UNIQUE, PRIMARY KEY, DEFAULT, CHECK, REFERENCES) the
// parser produces the dialect kinds below; the payload column says which of
// the constraint's fields carry the rest of the clause.
//
//	Type                              Payload
//	COMMENT                           Expr: the string literal (MySQL, MariaDB, ClickHouse)
//	CHARACTER SET                     Value: charset name; Keyword: CHARSET when written so
//	COLLATE                           Value: collation name as written (may be qualified or quoted)
//	ON UPDATE                         Expr: the expression (MySQL ON UPDATE CURRENT_TIMESTAMP)
//	INVISIBLE, VISIBLE                none (MySQL, MariaDB)
//	SRID                              Value: the spatial reference id (MySQL)
//	IDENTITY                          Args: "(seed, increment)" or "START n INCREMENT m" (T-SQL, Snowflake)
//	AUTO_INCREMENT                    AutoIncrement; Keyword: AUTOINCREMENT when written so; Args: Snowflake START/INCREMENT
//	GENERATED ALWAYS AS IDENTITY      Args: optional sequence options (PostgreSQL, Oracle)
//	GENERATED BY DEFAULT AS IDENTITY  Args: as above
//	GENERATED BY DEFAULT ON NULL AS IDENTITY  Args: as above (Oracle)
//	GENERATED ALWAYS AS               Expr: the generation expression; Keyword: STORED, VIRTUAL, PERSISTENT or PERSISTED
//	AS                                same, written without GENERATED ALWAYS
//	MATERIALIZED, ALIAS, EPHEMERAL    Expr: the expression (ClickHouse; EPHEMERAL may have none)
//	TTL                               Expr: the TTL expression (ClickHouse)
//	CODEC                             Args: "(Delta, ZSTD(1))" (ClickHouse)
//	DEFERRABLE, NOT DEFERRABLE, INITIALLY DEFERRED, INITIALLY IMMEDIATE   none
//	NOT FOR REPLICATION               none (T-SQL)
//
// PRIMARY KEY and UNIQUE may also carry Keyword CLUSTERED or NONCLUSTERED
// (T-SQL). Any constraint may carry Name (CONSTRAINT <name> ...).
//
// Table constraint kinds
//
// TableConstraint.Type is PRIMARY KEY, UNIQUE, FOREIGN KEY or CHECK, or:
//
//	KEY, INDEX    a MySQL index element: IndexName, Using, Columns/Exprs;
//	              ClickHouse INDEX instead has Exprs (one), Text (the TYPE
//	              clause) and Granularity
//	FULLTEXT, SPATIAL   a MySQL index element; Keyword is KEY or INDEX when written
//	LIKE          PostgreSQL / MySQL LIKE source_table: LikeTable, LikeOptions
//	PROJECTION    a ClickHouse projection: IndexName and Text (the "(SELECT ...)" body)
//	ASSUME        a ClickHouse assumed constraint: Check
//
// UNIQUE additionally takes Keyword (KEY or INDEX) and IndexName; PRIMARY KEY
// and UNIQUE take Cluster. Key parts with a prefix length or a sort order
// (name(191) DESC) keep that text in ColumnSuffix, parallel to Columns.

var (
	// The fixed vocabularies of the constraint fields that name a keyword;
	// the renderers write such a field only when it is one of these.
	clusterKeywords       = []string{"CLUSTERED", "NONCLUSTERED"}
	autoIncrementKeywords = []string{"AUTO_INCREMENT", "AUTOINCREMENT"}
	storageKeywords       = []string{"STORED", "VIRTUAL", "PERSISTENT", "PERSISTED"}
	indexKeywords         = []string{"KEY", "INDEX"}
	indexMethodKeywords   = []string{"BTREE", "HASH", "RTREE"}
	deferrableKeywords    = []string{
		"DEFERRABLE", "NOT DEFERRABLE",
		"DEFERRABLE INITIALLY DEFERRED", "DEFERRABLE INITIALLY IMMEDIATE",
		"NOT DEFERRABLE INITIALLY DEFERRED", "NOT DEFERRABLE INITIALLY IMMEDIATE",
		"INITIALLY DEFERRED", "INITIALLY IMMEDIATE",
	}
	likeOptionKeywords = []string{
		"INCLUDING ALL", "EXCLUDING ALL",
		"INCLUDING COMMENTS", "EXCLUDING COMMENTS",
		"INCLUDING COMPRESSION", "EXCLUDING COMPRESSION",
		"INCLUDING CONSTRAINTS", "EXCLUDING CONSTRAINTS",
		"INCLUDING DEFAULTS", "EXCLUDING DEFAULTS",
		"INCLUDING GENERATED", "EXCLUDING GENERATED",
		"INCLUDING IDENTITY", "EXCLUDING IDENTITY",
		"INCLUDING INDEXES", "EXCLUDING INDEXES",
		"INCLUDING STATISTICS", "EXCLUDING STATISTICS",
		"INCLUDING STORAGE", "EXCLUDING STORAGE",
	}
)

// releaseColumnConstraint returns the expressions a column constraint owns to
// their pools and clears every field, so a reused slot never carries state
// from an earlier statement.
func releaseColumnConstraint(c *ColumnConstraint) {
	PutExpression(c.Default)
	PutExpression(c.Check)
	PutExpression(c.Expr)
	*c = ColumnConstraint{}
}

// releaseTableConstraint returns the expressions a table constraint owns to
// their pools and clears every field. The Columns backing array is kept for
// reuse.
func releaseTableConstraint(t *TableConstraint) {
	PutExpression(t.Check)
	for i := range t.Exprs {
		PutExpression(t.Exprs[i])
		t.Exprs[i] = nil
	}
	cols := t.Columns[:0]
	*t = TableConstraint{Columns: cols}
}

// rawTextIsPlain reports whether s, the verbatim text of a parenthesised
// argument list or clause body (a ClickHouse CODEC or TYPE argument, a
// projection query, identity options), can be written back as is: its
// parentheses and brackets balance, its single-quoted segments are closed
// without backslashes, and it holds only characters the SQL operators and
// names use. Such text can neither end the statement nor start a comment.
func rawTextIsPlain(s string) bool {
	depth := 0
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch {
		case c == '\'':
			for i++; ; i++ {
				if i >= len(s) || s[i] == '\\' {
					return false
				}
				if s[i] == '\'' {
					if i+1 < len(s) && s[i+1] == '\'' {
						i++
						continue
					}
					break
				}
			}
		case c == '"' || c == '`':
			// A delimited identifier: closed, doubled delimiters, no escapes.
			j, ok := skipDelimited(s, i)
			if !ok {
				return false
			}
			i = j
		case c == '(' || c == '[':
			depth++
		case c == ')' || c == ']':
			depth--
			if depth < 0 {
				return false
			}
		case c == '-':
			if i+1 < len(s) && s[i+1] == '-' {
				return false
			}
		case c == '/':
			if i+1 < len(s) && s[i+1] == '*' {
				return false
			}
		case c == '_' || c == ' ' || c == ',' || c == '.' || c == '+' || c == '*' || c == '/' ||
			c == '%' || c == '<' || c == '>' || c == '=' || c == '!' || c == ':' || c == '|' ||
			c == '&' || c == '^' || c == '~' || c == '@' || c == '$' || c == '?',
			c|0x20 >= 'a' && c|0x20 <= 'z', c >= '0' && c <= '9', c >= 0x80:
		default:
			return false
		}
	}
	return depth == 0
}

// skipDelimited returns the index of the closing delimiter of the "..." or
// `...` segment of s that starts at i, treating a doubled delimiter as part of
// the name. It reports false when the segment is not closed or holds a
// backslash.
func skipDelimited(s string, i int) (int, bool) {
	q := s[i]
	for j := i + 1; j < len(s); j++ {
		switch s[j] {
		case '\\':
			return 0, false
		case q:
			if j+1 < len(s) && s[j+1] == q {
				j++
				continue
			}
			return j, true
		}
	}
	return 0, false
}

// qualifiedNameTextIsPlain reports whether s is a possibly dot-qualified name
// written as in the source: each part is a bare word or a quoted segment
// ("x", `x`, 'x'), so writing it back verbatim keeps its quoting.
func qualifiedNameTextIsPlain(s string) bool {
	if s == "" {
		return false
	}
	i := 0
	for {
		if i >= len(s) {
			return false
		}
		switch q := s[i]; q {
		case '"', '`', '\'':
			j := i + 1
			for {
				if j >= len(s) {
					return false
				}
				if s[j] == q {
					if j+1 < len(s) && s[j+1] == q {
						j += 2
						continue
					}
					break
				}
				if s[j] == '\\' {
					return false
				}
				j++
			}
			i = j + 1
		default:
			j := i
			for j < len(s) && (s[j] == '_' || s[j] == '$' || s[j] >= '0' && s[j] <= '9' ||
				s[j]|0x20 >= 'a' && s[j]|0x20 <= 'z' || s[j] >= 0x80) {
				j++
			}
			if j == i {
				return false
			}
			i = j
		}
		if i == len(s) {
			return true
		}
		if s[i] != '.' {
			return false
		}
		i++
	}
}

// keySuffixIsPlain reports whether s is a key part suffix: an optional
// "(length)" followed by an optional ASC or DESC.
func keySuffixIsPlain(s string) bool {
	if s == "" {
		return true
	}
	rest := s
	if rest[0] == '(' {
		j := 1
		for j < len(rest) && rest[j] >= '0' && rest[j] <= '9' {
			j++
		}
		if j == 1 || j >= len(rest) || rest[j] != ')' {
			return false
		}
		rest = rest[j+1:]
		if rest == "" {
			return true
		}
		if rest[0] != ' ' {
			return false
		}
		rest = rest[1:]
	}
	return keywordOneOf(rest, sortDirectionKeywords) != ""
}

// columnConstraintKinds lists the constraint kinds writeColumnConstraint
// gives a clause of their own, besides the bare keyword kinds of
// ColumnConstraintText.
var columnConstraintKinds = []string{
	"NOT NULL", "UNIQUE", "PRIMARY KEY", "DEFAULT", "REFERENCES", "CHECK",
	"COMMENT", "CHARACTER SET", "COLLATE", "ON UPDATE", "SRID", "IDENTITY",
	"AUTO_INCREMENT", "GENERATED ALWAYS AS IDENTITY", "GENERATED BY DEFAULT AS IDENTITY",
	"GENERATED BY DEFAULT ON NULL AS IDENTITY", "GENERATED ALWAYS AS", "AS",
	"MATERIALIZED", "ALIAS", "EPHEMERAL", "TTL", "CODEC",
}

// IsColumnConstraintKind reports whether s is a ColumnConstraint.Type the
// renderers write unchanged (any case for the bare keyword kinds, exact case
// for the others).
func IsColumnConstraintKind(s string) bool {
	for _, k := range columnConstraintKinds {
		if s == k {
			return true
		}
	}
	return ColumnConstraintText(s) == s
}

// IsTableConstraintKind reports whether s is a TableConstraint.Type the
// renderers write.
func IsTableConstraintKind(s string) bool {
	switch s {
	case "PRIMARY KEY", "UNIQUE", "FOREIGN KEY", "CHECK", "ASSUME", "KEY", "INDEX",
		"FULLTEXT", "SPATIAL", "LIKE", "PROJECTION":
		return true
	}
	return false
}
