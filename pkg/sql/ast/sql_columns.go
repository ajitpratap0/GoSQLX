package ast

import (
	"bytes"
	"strings"
)

// ColumnDefSQL renders a column definition (name, type and constraints).
func ColumnDefSQL(c *ColumnDef) string { return columnDefSQL(c) }

// ColumnConstraintSQL renders one column constraint.
func ColumnConstraintSQL(c *ColumnConstraint) string { return columnConstraintSQL(c) }

// TableConstraintSQL renders one table constraint or index element.
func TableConstraintSQL(tc *TableConstraint) string { return tableConstraintSQL(tc) }

func columnDefSQL(c *ColumnDef) string {
	sb := getBuf()
	defer putBuf(sb)
	writeTableAliasQ(sb, c.Name, c.NameQuote)
	if c.Type != "" {
		// A SQLite or ClickHouse column may have no type.
		sb.WriteString(" ")
		writeDataType(sb, c.Type)
	}
	for i := range c.Constraints {
		sb.WriteString(" ")
		writeColumnConstraint(sb, &c.Constraints[i])
	}
	return sb.String()
}

func columnConstraintSQL(c *ColumnConstraint) string {
	sb := getBuf()
	defer putBuf(sb)
	writeColumnConstraint(sb, c)
	return sb.String()
}

// writeNameText writes a name kept as source text (a charset or collation,
// possibly qualified or quoted); text that is not plainly shaped is dropped,
// which leaves a clause that does not parse.
func writeNameText(buf *bytes.Buffer, v string) {
	if qualifiedNameTextIsPlain(v) {
		buf.WriteString(v)
	}
}

// writeRawArgs writes the verbatim text of an argument list when it is plain.
func writeRawArgs(buf *bytes.Buffer, args string) {
	if args != "" && rawTextIsPlain(args) {
		buf.WriteString(args)
	}
}

// writeSpacedArgs writes args after a space, or nothing when there are none.
func writeSpacedArgs(buf *bytes.Buffer, args string) {
	if args != "" && rawTextIsPlain(args) {
		buf.WriteByte(' ')
		buf.WriteString(args)
	}
}

// writeGeneratedExpr writes a generation expression, parenthesised unless
// it already is.
func writeGeneratedExpr(buf *bytes.Buffer, e Expression) {
	if _, ok := e.(*ParenthesizedExpression); ok {
		writeExpr(buf, e)
		return
	}
	buf.WriteByte('(')
	writeExpr(buf, e)
	buf.WriteByte(')')
}

func writeColumnConstraint(buf *bytes.Buffer, c *ColumnConstraint) {
	if c.Name != "" {
		buf.WriteString("CONSTRAINT ")
		writeConstraintName(buf, c.Name)
		buf.WriteString(" ")
	}
	switch c.Type {
	case "NOT NULL", "UNIQUE", "PRIMARY KEY":
		buf.WriteString(c.Type)
		if kw := keywordOneOf(c.Keyword, clusterKeywords); kw != "" && c.Type != "NOT NULL" {
			buf.WriteString(" ")
			buf.WriteString(kw)
		}
	case "DEFAULT":
		buf.WriteString("DEFAULT ")
		writeExpr(buf, c.Default)
	case "REFERENCES":
		if c.References != nil {
			buf.WriteString(referenceSQL(c.References))
		} else {
			buf.WriteString("REFERENCES")
		}
	case "CHECK":
		buf.WriteString("CHECK (")
		writeExpr(buf, c.Check)
		buf.WriteString(")")
	case "COMMENT":
		buf.WriteString("COMMENT ")
		writeExpr(buf, c.Expr)
	case "CHARACTER SET":
		if strings.EqualFold(c.Keyword, "CHARSET") {
			buf.WriteString("CHARSET ")
		} else {
			buf.WriteString("CHARACTER SET ")
		}
		writeNameText(buf, c.Value)
	case "COLLATE":
		buf.WriteString("COLLATE ")
		writeNameText(buf, c.Value)
	case "ON UPDATE":
		buf.WriteString("ON UPDATE ")
		writeExpr(buf, c.Expr)
	case "SRID":
		buf.WriteString("SRID ")
		if isDigits(c.Value) {
			buf.WriteString(c.Value)
		}
	case "IDENTITY":
		buf.WriteString("IDENTITY")
		if strings.HasPrefix(c.Args, "(") {
			writeRawArgs(buf, c.Args)
		} else {
			writeSpacedArgs(buf, c.Args)
		}
	case "AUTO_INCREMENT":
		writeAutoIncrement(buf, c)
	case "GENERATED ALWAYS AS IDENTITY", "GENERATED BY DEFAULT AS IDENTITY",
		"GENERATED BY DEFAULT ON NULL AS IDENTITY":
		buf.WriteString(c.Type)
		writeSpacedArgs(buf, c.Args)
	case "GENERATED ALWAYS AS", "AS":
		buf.WriteString(c.Type)
		buf.WriteString(" ")
		writeGeneratedExpr(buf, c.Expr)
		if kw := keywordOneOf(c.Keyword, storageKeywords); kw != "" {
			buf.WriteString(" ")
			buf.WriteString(kw)
		}
	case "MATERIALIZED", "ALIAS", "EPHEMERAL":
		buf.WriteString(c.Type)
		if c.Expr != nil {
			buf.WriteString(" ")
			writeExpr(buf, c.Expr)
		}
	case "TTL":
		buf.WriteString("TTL ")
		writeExpr(buf, c.Expr)
	case "CODEC":
		buf.WriteString("CODEC")
		writeRawArgs(buf, c.Args)
	default:
		if c.AutoIncrement {
			writeAutoIncrement(buf, c)
			return
		}
		// An unknown constraint kind is dropped.
		buf.WriteString(ColumnConstraintText(c.Type))
	}
}

// writeAutoIncrement writes AUTO_INCREMENT or, when the source used it,
// AUTOINCREMENT (SQLite, Snowflake), with the Snowflake START / INCREMENT
// arguments.
func writeAutoIncrement(buf *bytes.Buffer, c *ColumnConstraint) {
	if keywordOneOf(c.Keyword, autoIncrementKeywords) != "" {
		buf.WriteString(strings.ToUpper(c.Keyword))
	} else {
		buf.WriteString("AUTO_INCREMENT")
	}
	writeSpacedArgs(buf, c.Args)
}

func isDigits(s string) bool {
	if s == "" {
		return false
	}
	for i := 0; i < len(s); i++ {
		if s[i] < '0' || s[i] > '9' {
			return false
		}
	}
	return true
}

func tableConstraintSQL(tc *TableConstraint) string {
	sb := getBuf()
	defer putBuf(sb)
	writeTableConstraint(sb, tc)
	return sb.String()
}

// writeKeyParts writes the parenthesised key part list of an index or key
// constraint: plain column names with their prefix length and sort order, or
// the expression parts of a functional index.
func writeKeyParts(buf *bytes.Buffer, tc *TableConstraint) {
	buf.WriteString("(")
	if len(tc.Exprs) > 0 {
		for i, e := range tc.Exprs {
			if i > 0 {
				buf.WriteString(", ")
			}
			if _, ok := e.(*Identifier); ok {
				writeExpr(buf, e)
				continue
			}
			buf.WriteByte('(')
			writeExpr(buf, e)
			buf.WriteByte(')')
		}
	} else {
		for i, n := range tc.Columns {
			if i > 0 {
				buf.WriteString(", ")
			}
			writeTableAliasQ(buf, n, nameQuoteAt(tc.ColumnQuotes, i))
			if i < len(tc.ColumnSuffix) && keySuffixIsPlain(tc.ColumnSuffix[i]) {
				sfx := tc.ColumnSuffix[i]
				if strings.HasPrefix(sfx, "(") || sfx == "" {
					buf.WriteString(sfx)
				} else {
					buf.WriteString(" ")
					buf.WriteString(sfx)
				}
			}
		}
	}
	buf.WriteString(")")
}

// writeIndexHead writes the optional KEY / INDEX word, index name and index
// method that precede the key parts of an index element.
func writeIndexHead(buf *bytes.Buffer, tc *TableConstraint) {
	if kw := keywordOneOf(tc.Keyword, indexKeywords); kw != "" {
		buf.WriteString(" ")
		buf.WriteString(kw)
	}
	if tc.IndexName != "" {
		buf.WriteString(" ")
		writeTableAliasQ(buf, tc.IndexName, tc.IndexNameQuote)
	}
	if m := keywordOneOf(tc.Using, indexMethodKeywords); m != "" {
		buf.WriteString(" USING ")
		buf.WriteString(m)
	}
}

func writeDeferrable(buf *bytes.Buffer, tc *TableConstraint) {
	if d := keywordOneOf(tc.Deferrable, deferrableKeywords); d != "" {
		buf.WriteString(" ")
		buf.WriteString(d)
	}
}

func writeTableConstraint(buf *bytes.Buffer, tc *TableConstraint) {
	if tc.Name != "" {
		buf.WriteString("CONSTRAINT ")
		writeConstraintNameQ(buf, tc.Name, tc.NameQuote)
		buf.WriteString(" ")
	}
	switch tc.Type {
	case "PRIMARY KEY":
		buf.WriteString("PRIMARY KEY")
		if kw := keywordOneOf(tc.Cluster, clusterKeywords); kw != "" {
			buf.WriteString(" ")
			buf.WriteString(kw)
		}
		buf.WriteString(" ")
		writeKeyParts(buf, tc)
		writeDeferrable(buf, tc)
	case "UNIQUE":
		buf.WriteString("UNIQUE")
		writeIndexHead(buf, tc)
		if kw := keywordOneOf(tc.Cluster, clusterKeywords); kw != "" {
			buf.WriteString(" ")
			buf.WriteString(kw)
		}
		buf.WriteString(" ")
		writeKeyParts(buf, tc)
		writeDeferrable(buf, tc)
	case "FOREIGN KEY":
		buf.WriteString("FOREIGN KEY (")
		writeColumnNameListQ(buf, tc.Columns, tc.ColumnQuotes)
		buf.WriteString(") ")
		if tc.References != nil {
			buf.WriteString(referenceSQL(tc.References))
		}
		writeDeferrable(buf, tc)
	case "CHECK":
		buf.WriteString("CHECK (")
		writeExpr(buf, tc.Check)
		buf.WriteString(")")
		writeDeferrable(buf, tc)
	case "ASSUME":
		buf.WriteString("ASSUME ")
		writeExpr(buf, tc.Check)
	case "KEY", "INDEX":
		if tc.Text != "" {
			writeClickHouseIndex(buf, tc)
			return
		}
		buf.WriteString(tc.Type)
		if tc.IndexName != "" {
			buf.WriteString(" ")
			writeTableAliasQ(buf, tc.IndexName, tc.IndexNameQuote)
		}
		if m := keywordOneOf(tc.Using, indexMethodKeywords); m != "" {
			buf.WriteString(" USING ")
			buf.WriteString(m)
		}
		buf.WriteString(" ")
		writeKeyParts(buf, tc)
	case "FULLTEXT", "SPATIAL":
		buf.WriteString(tc.Type)
		writeIndexHead(buf, tc)
		buf.WriteString(" ")
		writeKeyParts(buf, tc)
	case "LIKE":
		buf.WriteString("LIKE ")
		writeQualifiedNameQ(buf, tc.LikeTable, tc.LikeTableQuote)
		for _, o := range tc.LikeOptions {
			if kw := keywordOneOf(o, likeOptionKeywords); kw != "" {
				buf.WriteString(" ")
				buf.WriteString(kw)
			}
		}
	case "PROJECTION":
		buf.WriteString("PROJECTION ")
		writeTableAliasQ(buf, tc.IndexName, tc.IndexNameQuote)
		writeSpacedArgs(buf, tc.Text)
	default:
		// The parser only stores the kinds above; any other kind can only
		// come from a hand-built AST and is dropped, leaving a constraint
		// without a kind, which does not parse.
	}
}

// writeClickHouseIndex writes INDEX name expr TYPE type GRANULARITY n.
func writeClickHouseIndex(buf *bytes.Buffer, tc *TableConstraint) {
	buf.WriteString("INDEX ")
	writeTableAliasQ(buf, tc.IndexName, tc.IndexNameQuote)
	if len(tc.Exprs) > 0 {
		buf.WriteString(" ")
		writeExpr(buf, tc.Exprs[0])
	}
	if rawTextIsPlain(tc.Text) {
		buf.WriteString(" TYPE ")
		buf.WriteString(tc.Text)
	}
	if isDigits(tc.Granularity) {
		buf.WriteString(" GRANULARITY ")
		buf.WriteString(tc.Granularity)
	}
}
