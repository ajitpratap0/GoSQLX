func TestDialectConstructsDDLRoundTrip(t *testing.T) {
	cases := []struct {
		dialect keywords.SQLDialect
		sql     string
	}{
		{keywords.DialectPostgreSQL, "CREATE TABLE t (id bigint GENERATED ALWAYS AS IDENTITY (START WITH 10 INCREMENT BY 5) PRIMARY KEY, b int GENERATED BY DEFAULT AS IDENTITY NOT NULL, c int NOT NULL GENERATED ALWAYS AS IDENTITY)"},
		{keywords.DialectMySQL, "ALTER TABLE t PARTITION BY RANGE (YEAR(d)) (PARTITION p0 VALUES LESS THAN (2020), PARTITION p1 VALUES LESS THAN MAXVALUE)"},
		{keywords.DialectMySQL, "ALTER TABLE t ADD PARTITION (PARTITION p2 VALUES LESS THAN (2030))"},
		{keywords.DialectMySQL, "ALTER TABLE t DROP PARTITION p0"},
		{keywords.DialectMySQL, "ALTER TABLE t DROP PARTITION p1, p2"},
		{keywords.DialectMySQL, "ALTER TABLE t TRUNCATE PARTITION p1"},
		{keywords.DialectMySQL, "ALTER TABLE t REORGANIZE PARTITION p1 INTO (PARTITION p2 VALUES LESS THAN (2030))"},
		{keywords.DialectMySQL, "ALTER TABLE t REMOVE PARTITIONING"},
		{keywords.DialectMySQL, "ALTER TABLE t DROP PARTITION `2020`"},
		{keywords.DialectMySQL, "ALTER TABLE t TRUNCATE PARTITION `p-0`"},
		{keywords.DialectMySQL, "ALTER TABLE t REORGANIZE PARTITION `p-0` INTO (PARTITION p2 VALUES LESS THAN (2030))"},
		{keywords.DialectMySQL, "ALTER TABLE t PARTITION BY LIST (d) (PARTITION p VALUES IN (1, 2))"},
		{keywords.DialectMySQL, "ALTER TABLE t PARTITION BY HASH (d) PARTITIONS 4"},
		{keywords.DialectMariaDB, "ALTER TABLE t PARTITION BY SYSTEM_TIME INTERVAL 1 MONTH (PARTITION p_old HISTORY, PARTITION p_cur CURRENT)"},
	}
	for _, tc := range cases {
		t.Run(tc.sql, func(t *testing.T) {
			tree, err := gosqlx.ParseWithDialect(tc.sql, tc.dialect)
			if err != nil {
				t.Fatal(err)
			}
			defer ast.ReleaseAST(tree)
			if tc.dialect == keywords.DialectMySQL {
				stmt, ok := tree.Statements[0].(*ast.AlterStatement)
				if !ok {
					t.Fatalf("got %T", tree.Statements[0])
				}
				op, ok := stmt.Operation.(*ast.AlterTableOperation)
				if !ok {
					t.Fatalf("got %T", stmt.Operation)
				}
				if op.Type != ast.AlterPartitioning {
					t.Fatalf("partition action has type %v", op.Type)
				}
				visited := map[ast.Node]bool{}
				ast.Inspect(stmt, func(node ast.Node) bool {
					if node != nil {
						visited[node] = true
					}
					return true
				})
				for _, def := range op.PartitionDefinitions {
					if def.LessThan != nil && !visited[def.LessThan] {
						t.Error("partition boundary not visited")
					}
				}
				if op.Partitioning != nil {
					for _, expr := range op.Partitioning.Expressions {
						if !visited[expr] {
							t.Error("partition key not visited")
						}
					}
				}
			}
			formatted, err := gosqlx.FormatWithDialect(tc.sql, gosqlx.DefaultFormatOptions(), tc.dialect)
			if err != nil {
				t.Fatal(err)
			}
			writer, ok := tree.Statements[0].(interface{ SQL() string })
			if !ok {
				t.Fatalf("statement %T lacks SQL", tree.Statements[0])
			}
			for _, rendered := range []string{writer.SQL(), formatted} {
				other, err := gosqlx.ParseWithDialect(rendered, tc.dialect)
				if err != nil {
					t.Fatalf("reparse %q: %v", rendered, err)
				}
				defer ast.ReleaseAST(other)
				clearDDLSourcePositions(reflect.ValueOf(tree))
				clearDDLSourcePositions(reflect.ValueOf(other))
				if !reflect.DeepEqual(tree.Statements, other.Statements) {
					t.Errorf("tree changed after rendering %q", rendered)
				}
			}
		})
	}
}

// Source locations are metadata and change when the formatter inserts line breaks.
func clearDDLSourcePositions(v reflect.Value) {
	if !v.IsValid() {
		return
	}
	if v.Type() == reflect.TypeOf(models.Location{}) && v.CanSet() {
		v.Set(reflect.Zero(v.Type()))
		return
	}
	switch v.Kind() {
	case reflect.Pointer, reflect.Interface:
		if !v.IsNil() {
			clearDDLSourcePositions(v.Elem())
		}
	case reflect.Struct:
		for i := 0; i < v.NumField(); i++ {
			clearDDLSourcePositions(v.Field(i))
		}
	case reflect.Slice:
		for i := 0; i < v.Len(); i++ {
			clearDDLSourcePositions(v.Index(i))
		}
	}
}

func TestDialectConstructsPartitionMalformed(t *testing.T) {
	for _, sql := range []string{
		"ALTER TABLE t PARTITION BY SYSTEM_TIME INTERVAL 1 MONTH",
		"ALTER TABLE t PARTITION BY RANGE (d) (PARTITION p VALUES IN (1))",
		"ALTER TABLE t PARTITION BY RANGE COLUMNS (d) (PARTITION p VALUES IN (1))",
		"ALTER TABLE t PARTITION BY LIST (d) (PARTITION p VALUES LESS THAN (1))",
		"ALTER TABLE t PARTITION BY LIST COLUMNS (d) (PARTITION p VALUES LESS THAN (1))",
		"ALTER TABLE t PARTITION BY HASH (d) (PARTITION p VALUES IN (1))",
		"ALTER TABLE t PARTITION BY KEY (d) (PARTITION p VALUES LESS THAN (1))",
		"ALTER TABLE t PARTITION BY RANGE (d) INTERVAL (1)",
		"ALTER TABLE t PARTITION BY RANGE (YEAR(d)) (PARTITION p VALUES LESS THAN)",
	} {
		t.Run(sql, func(t *testing.T) {
			tree, err := gosqlx.ParseWithDialect(sql, keywords.DialectMySQL)
			if err == nil {
				ast.ReleaseAST(tree)
				t.Fatal("expected syntax error")
			}
		})
	}
}

// TestDialectConstructsPartitionFallback covers partition actions outside the
// structured grammar that earlier releases accepted as as-written text: they
// still parse, as AlterTableOther, and round-trip.
func TestDialectConstructsPartitionFallback(t *testing.T) {
	for _, sql := range []string{
		"ALTER TABLE t ADD PARTITION ()",
		"ALTER TABLE t DROP PARTITION",
		"ALTER TABLE t DROP PARTITION 123",
		"ALTER TABLE t DROP PARTITION 'p0'",
		"ALTER TABLE t TRUNCATE PARTITION 1.5",
		"ALTER TABLE t TRUNCATE PARTITION 'p0'",
		"ALTER TABLE t REORGANIZE PARTITION 123 INTO (PARTITION p2 VALUES LESS THAN (2030))",
		"ALTER TABLE t REORGANIZE PARTITION 'p0' INTO (PARTITION p2 VALUES LESS THAN (2030))",
		"ALTER TABLE t REORGANIZE PARTITION p INTO ()",
		"ALTER TABLE t ADD PARTITION (PARTITION p0 VALUES LESS THAN (10) ENGINE = InnoDB)",
		"ALTER TABLE t DROP PARTITION IF EXISTS p0",
		"ALTER TABLE t CONVERT PARTITION p TO TABLE t2",
	} {
		t.Run(sql, func(t *testing.T) {
			tree, err := gosqlx.ParseWithDialect(sql, keywords.DialectMySQL)
			if err != nil {
				t.Fatalf("parse: %v", err)
			}
			defer ast.ReleaseAST(tree)
			stmt, ok := tree.Statements[0].(*ast.AlterStatement)
			if !ok {
				t.Fatalf("got %T", tree.Statements[0])
			}
			op, ok := stmt.Operation.(*ast.AlterTableOperation)
			if !ok || op.Type != ast.AlterTableOther {
				t.Fatalf("operation = %#v, want AlterTableOther", stmt.Operation)
			}
			out := tree.SQL()
			again, err := gosqlx.ParseWithDialect(out, keywords.DialectMySQL)
			if err != nil {
				t.Fatalf("reparse %q: %v", out, err)
			}
			defer ast.ReleaseAST(again)
			if got := again.SQL(); got != out {
				t.Fatalf("round trip: %q != %q", got, out)
			}
		})
	}
}
