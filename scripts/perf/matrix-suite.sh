#!/usr/bin/env bash
# matrix-suite.sh - print the full benchmark matrix as a perf-gate suite file
# (the format of scripts/perf/gate-suite.txt) for the "matrix" dispatch mode of
# .github/workflows/perf-gate.yml: every package under ./pkg and
# ./wasm/internal that has benchmarks, with the regex "." (the packages
# `task bench:matrix` runs), except pkg/cbinding, which needs CGO
# (`task test:cbinding` covers it). The list is generated, so a package that
# gains benchmarks joins the matrix without editing a file.
#
# Usage: scripts/perf/matrix-suite.sh [REPO_ROOT] > suite.txt
#        scripts/perf/ab.sh -s suite.txt BASE
set -euo pipefail
root=${1:-$(git rev-parse --show-toplevel)}
cd "$root"
echo "# Full benchmark matrix, generated by scripts/perf/matrix-suite.sh"
grep -rlE --include='*_test.go' '^func Benchmark[A-Za-z0-9_]*\(' pkg wasm/internal |
	sed 's#/[^/]*$##' | sort -u | grep -vx 'pkg/cbinding' | sed -e 's#^#./#' -e 's#$# .#'
